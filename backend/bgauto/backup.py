"""One-file backups of the pilot's state (``plan/06`` section 6).

The zip holds the things that cannot be regenerated by reading the code:

* a custom-format ``pg_dump`` of the PostgreSQL register and audit trail,
* the review workbook,
* the tracker template and every uploaded PDF.

Restore is deliberately manual (:func:`restore_hint`): a restore overwrites the
live register, so an operator should do it with the app stopped, not a button.
"""
from __future__ import annotations

import datetime as dt
import os
import shutil
import subprocess
import zipfile
from pathlib import Path

from psycopg.conninfo import conninfo_to_dict, make_conninfo

from . import config

PREFIX = "bg-auto-backup-"
DUMP_NAME = "database.dump"


def _files() -> list[Path]:
    candidates = [
        config.TRACKER_PATH,
        config.WORKBOOK_PATH,
    ]
    pdf_root = config.PDF_ARCHIVE_DIR
    if pdf_root.is_dir():
        candidates.extend(sorted(pdf_root.rglob("*.pdf")))
    return [path for path in candidates if path.is_file()]


def _dump_command(target: Path) -> tuple[list[str], dict[str, str]]:
    """Build the pg_dump call, keeping the password out of the argv list."""
    url = (config.DATABASE_URL or "").strip()
    if not url:
        raise RuntimeError("DATABASE_URL is not set, so the register cannot be dumped.")
    executable = shutil.which("pg_dump")
    if not executable:
        raise FileNotFoundError(
            "pg_dump was not found on PATH. Install the PostgreSQL client "
            "(the container image already includes it)."
        )
    params = conninfo_to_dict(url)
    password = params.pop("password", None)
    env = dict(os.environ)
    if password:
        env["PGPASSWORD"] = password
    command = [
        executable,
        "--format=custom",
        "--no-owner",
        "--file",
        str(target),
        "--dbname",
        make_conninfo(**params),
    ]
    return command, env


def _pg_dump(target: Path) -> None:
    command, env = _dump_command(target)
    completed = subprocess.run(
        command, capture_output=True, text=True, check=False, env=env
    )
    if completed.returncode != 0:
        detail = (completed.stderr or "").strip().splitlines()
        reason = detail[-1] if detail else f"exit {completed.returncode}"
        raise RuntimeError(f"pg_dump failed: {reason}")


def create_backup(
    *,
    backup_dir: Path | None = None,
    keep: int | None = None,
    workbook_path: Path | None = None,
    tracker_path: Path | None = None,
) -> dict:
    """Write ``bg-auto-backup-YYYYMMDD-HHMMSS.zip`` and prune old copies."""
    target_dir = Path(backup_dir or config.BACKUP_DIR)
    target_dir.mkdir(parents=True, exist_ok=True)
    keep = config.BACKUP_KEEP if keep is None else max(1, int(keep))

    saved = (config.WORKBOOK_PATH, config.TRACKER_PATH)
    try:
        if workbook_path is not None:
            config.WORKBOOK_PATH = Path(workbook_path)
        if tracker_path is not None:
            config.TRACKER_PATH = Path(tracker_path)
        files = _files()
    finally:
        config.WORKBOOK_PATH, config.TRACKER_PATH = saved

    stamp = dt.datetime.now().strftime("%Y%m%d-%H%M%S")
    archive = target_dir / f"{PREFIX}{stamp}.zip"
    dump = target_dir / f".{PREFIX}{stamp}.dump"
    try:
        _pg_dump(dump)
        with zipfile.ZipFile(archive, "w", compression=zipfile.ZIP_DEFLATED) as zipped:
            zipped.write(dump, DUMP_NAME)
            for path in files:
                try:
                    arcname = str(path.resolve().relative_to(config.REPO_ROOT))
                except ValueError:
                    arcname = path.name
                zipped.write(path, arcname)
    except Exception:
        archive.unlink(missing_ok=True)
        raise
    finally:
        dump.unlink(missing_ok=True)

    removed: list[str] = []
    existing = sorted(target_dir.glob(f"{PREFIX}*.zip"))
    for old in existing[:-keep]:
        try:
            old.unlink()
            removed.append(old.name)
        except OSError:
            pass

    return {
        "archive": str(archive),
        "database": DUMP_NAME,
        "files": len(files) + 1,
        "bytes": archive.stat().st_size,
        "kept": min(len(existing), keep),
        "removed": removed,
    }


def restore_hint(archive: Path | None = None) -> str:
    name = str(archive or f"{PREFIX}YYYYMMDD-HHMMSS.zip")
    return (
        "Stop the app first, unzip the archive, then restore the register with "
        "pg_restore --clean --if-exists --no-owner --dbname \"$DATABASE_URL\" "
        "database.dump and copy out/BG Tracker_ingested.xlsx and data/pdfs/ back "
        "into place. Start the app and check GET /api/health, the Register screen "
        "and one reminder dry run.\n"
        f"Archive: {name}"
    )
