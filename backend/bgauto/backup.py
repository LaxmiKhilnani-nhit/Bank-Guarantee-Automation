"""One-file backups of the pilot's state (``plan/06`` section 6).

The zip holds the three things that cannot be regenerated by reading the code:

* the SQLite register and audit trail,
* the review workbook,
* the tracker template and every uploaded PDF.

Restore is deliberately manual (:func:`restore_hint`): a restore overwrites the
live register, so an operator should do it with the app stopped, not a button.
"""
from __future__ import annotations

import datetime as dt
import zipfile
from pathlib import Path

from . import config

PREFIX = "bg-auto-backup-"


def _files() -> list[Path]:
    candidates = [
        config.DB_PATH,
        config.TRACKER_PATH,
        config.WORKBOOK_PATH,
    ]
    pdf_root = config.PDF_ARCHIVE_DIR
    if pdf_root.is_dir():
        candidates.extend(sorted(pdf_root.rglob("*.pdf")))
    return [path for path in candidates if path.is_file()]


def create_backup(
    *,
    backup_dir: Path | None = None,
    keep: int | None = None,
    db_path: Path | None = None,
    workbook_path: Path | None = None,
    tracker_path: Path | None = None,
) -> dict:
    """Write ``bg-auto-backup-YYYYMMDD-HHMMSS.zip`` and prune old copies."""
    target_dir = Path(backup_dir or config.BACKUP_DIR)
    target_dir.mkdir(parents=True, exist_ok=True)
    keep = config.BACKUP_KEEP if keep is None else max(1, int(keep))

    saved = (config.DB_PATH, config.WORKBOOK_PATH, config.TRACKER_PATH)
    try:
        if db_path is not None:
            config.DB_PATH = Path(db_path)
        if workbook_path is not None:
            config.WORKBOOK_PATH = Path(workbook_path)
        if tracker_path is not None:
            config.TRACKER_PATH = Path(tracker_path)
        files = _files()
    finally:
        config.DB_PATH, config.WORKBOOK_PATH, config.TRACKER_PATH = saved

    if not files:
        raise FileNotFoundError("Nothing to back up: no database, workbook or PDFs were found.")

    stamp = dt.datetime.now().strftime("%Y%m%d-%H%M%S")
    archive = target_dir / f"{PREFIX}{stamp}.zip"
    with zipfile.ZipFile(archive, "w", compression=zipfile.ZIP_DEFLATED) as zipped:
        for path in files:
            try:
                arcname = str(path.resolve().relative_to(config.REPO_ROOT))
            except ValueError:
                arcname = path.name
            zipped.write(path, arcname)

    removed: list[str] = []
    existing = sorted(target_dir.glob(f"{PREFIX}*.zip"))
    for old in existing[:-keep]:
        try:
            old.unlink()
            removed.append(old.name)
        except OSError:
            pass

    return {
        "archive": str(archive),
        "files": len(files),
        "bytes": archive.stat().st_size,
        "kept": min(len(existing), keep),
        "removed": removed,
    }


def restore_hint(archive: Path | None = None) -> str:
    name = str(archive or f"{PREFIX}YYYYMMDD-HHMMSS.zip")
    return (
        "Stop the app first, then unzip the archive over the repo root so "
        "db/sqlite/bg_automation.sqlite3, out/BG Tracker_ingested.xlsx and "
        "data/pdfs/ are replaced together. Start the app and check "
        "GET /api/health, the Register screen and one reminder dry run.\n"
        f"Archive: {name}"
    )
